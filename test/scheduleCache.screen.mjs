import './emulatorConfig.mjs';
import { browserOrigin } from './emulatorConfig.mjs';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import puppeteer from 'puppeteer';
import assert from 'node:assert/strict';
import { recordAppReadChange } from '../functions/lib/appReadChanges.js';
const require=createRequire(new URL('../functions/package.json',import.meta.url));
const {initializeApp}=require('firebase-admin/app'),{getFirestore}=require('firebase-admin/firestore');
const db=getFirestore(initializeApp({projectId:'demo-clean-manager'},'cache-browser'));
const companyId='qa_pagination',root=`companies/${companyId}`,id='cache_browser_'+Date.now();
const date=new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Seoul'});
const original={title:'저장된 캐시 먼저 표시 '+id,calId:'team1',start:date,end:date};
const ref=db.doc(`${root}/events/${id}`);
await ref.set(original);
if(!(await db.doc(`${root}/meta/readRevision`).get()).exists)await db.doc(`${root}/meta/readRevision`).set({revision:1000});
const browser=await puppeteer.launch({headless:true,args:['--window-position=-32000,-32000']});
const page=await browser.newPage();const errors=[],responses=[],pending=[];let hold=false;
page.on('pageerror',e=>errors.push(e.message));
await page.setRequestInterception(true);
page.on('request',request=>{if(hold&&request.method()==='POST'&&request.url().endsWith('/appReadData'))pending.push(request);else request.continue();});
page.on('response',async response=>{if(response.url().endsWith('/appReadData'))try{responses.push({request:JSON.parse(response.request().postData()).data,data:(await response.json()).result});}catch{}});
const wait=text=>page.waitForFunction(text=>document.body.innerText.includes(text),{timeout:30000},text);
try{
  await page.goto(browserOrigin,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('input[placeholder="아이디 또는 전화번호"]');await page.type('input[placeholder="아이디 또는 전화번호"]','qaowner');
  await page.type('input[placeholder="비밀번호"]','qa-local-only');
  await page.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='로그인').click());
  await wait(original.title);await page.waitForNetworkIdle({idleTime:500,timeout:10000}).catch(()=>{});
  // Await durable IndexedDB commit, not merely a React state render.
  assert.ok(await page.evaluate(async()=>{const {readScheduleCache}=await import('/src/lib/scheduleCache.js');const db=await new Promise(resolve=>{const r=indexedDB.open('clean-manager-schedule-v1');r.onsuccess=()=>resolve(r.result);});return await new Promise(resolve=>{const r=db.transaction('snapshots').objectStore('snapshots').getAll();r.onsuccess=()=>resolve(r.result.some(r=>r.data.events.length));});}));
  hold=true;responses.length=0;
  await page.reload({waitUntil:'domcontentloaded'});await wait(original.title);
  assert.equal(responses.length,0,'cached event renders before any data response');
  console.log('PASS closed/reloaded app displays durable local schedule before server responds');
  hold=false;for(const request of pending.splice(0))await request.continue();
  await page.waitForFunction(()=>!document.body.innerText.includes('서버 자료 확인 중'),{timeout:30000});
  await page.waitForNetworkIdle({idleTime:500,timeout:10000}).catch(()=>{});
  assert.ok(responses.some(r=>r.data?.notModified&&r.request.knownRevision!==undefined));
  assert.ok(responses.every(r=>!r.data?.events),'unchanged relaunch sends no event arrays');
  console.log('PASS unchanged relaunch confirms revision and transfers no event/report payload');
  const before=await ref.get();await ref.set({...original,title:'변경 한 건만 반영 '+id});
  await recordAppReadChange(db,{id:randomUUID(),params:{companyId,id},data:{before,after:await ref.get()}},'events');
  await wait('변경 한 건만 반영 '+id);await page.waitForNetworkIdle({idleTime:500,timeout:10000}).catch(()=>{});
  const delta=responses.find(r=>r.data?.delta);
  assert.ok(delta);assert.deepEqual(delta.data.events.map(e=>e.id),[id]);
  console.log('PASS one changed source updates actual calendar without returning unchanged schedule documents');
  await page.evaluate(async()=>{const {endSession}=await import('/src/lib/appAuth.js');await endSession();});
  const count=await page.evaluate(async()=>{const db=await new Promise(resolve=>{const r=indexedDB.open('clean-manager-schedule-v1');r.onsuccess=()=>resolve(r.result);});return await new Promise(resolve=>{const r=db.transaction('snapshots').objectStore('snapshots').count();r.onsuccess=()=>resolve(r.result);});});
  assert.equal(count,0,'logout clears persisted business snapshot');assert.deepEqual(errors,[]);
  console.log('PASS logout clears persistent schedule data; browser errors empty');
}finally{hold=false;for(const request of pending.splice(0))await request.abort().catch(()=>{});await browser.close();await db.terminate();}
